const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const sandbox={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/activityMetrics.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,sandbox);
const m=sandbox.exports,start=Date.parse('2026-10-09T06:00:00Z');
const at=s=>new Date(start+s*1000).toISOString();
const series=m.heartRateSeries([{startDate:at(-1),value:80},{startDate:at(30),value:120},{startDate:at(30),value:140},{startDate:at(60),value:150},{startDate:at(70),value:NaN},{startDate:at(80),value:-1},{startDate:at(301),value:160}],start,start+300000);
assert.equal(series.length,2);assert.equal(series[0].seconds,30);assert.equal(series[0].value,130);
assert.equal(m.timeBounds('bad',300),null);assert.equal(m.timeBounds(at(0),0),null);
assert.equal(m.formatPace(5.999),'6:00');assert.equal(m.formatPace(0),'—');
const latitude=meters=>meters/6371000*180/Math.PI;
const route=Array.from({length:26},(_,i)=>({latitude:latitude(i*50),longitude:0,timestamp:at(i*10),speed:5,altitude:100+i}));
assert.equal(m.workoutLocations({data:{locations:[...route,{latitude:100,longitude:0,timestamp:at(50)}]}},start,start+250000).length,26);
const graphs=m.routeSeries(route,start);assert.equal(graphs.speed[0].value,18);assert(Math.abs(graphs.pace[0].value-3.333333)<0.001);
const split=m.routeSplits(route,1000);assert.equal(split.length,2);assert.equal(split[0].partial,false);assert(Math.abs(split[0].seconds-200)<0.01);assert(Math.abs(split[1].distance-250)<0.01);
const stopped=m.routeSeries(route.map((p,i)=>({...p,speed:i===5?0:5})),start);assert(stopped.pace.find(p=>p.seconds===60).breakBefore);
const gap=route.map((p,i)=>({...p,timestamp:at(i*10+(i>=10?180:0))}));assert(m.routeSplits(gap,1000).every(s=>s.partial));
assert.equal(m.routeSplits(route,0).length,0);
assert.equal(m.routeSeries([{...route[0],speed:-1}],start).speed.length,0);
console.log('PASS: workout time bounds, heart-rate filtering/deduplication, speed/pace units, split interpolation, stationary gaps and missing-route handling.');
